// Helper to format links and emails
// ────────────────────────────────────────────────────────

const formatTextWithLinks = (text) => {
  const urlRegex = /(https?:\/\/[^\s]+)/g;
  const emailRegex =
    /([a-zA-Z0-9._-]+@[a-zA-Z0-9._-]+\.[a-zA-Z0-9_-]+)/g;

  const parts = text.split(urlRegex);

  return parts.map((part, i) => {
    if (part.match(urlRegex)) {
      return (
        <a
          key={i}
          href={part}
          target="_blank"
          rel="noopener noreferrer"
          className="text-[#1260B2] hover:underline break-all font-medium"
        >
          {part}
        </a>
      );
    }

    const emailParts = part.split(emailRegex);

    return emailParts.map((subPart, j) => {
      if (subPart.match(emailRegex)) {
        return (
          <a
            key={`${i}-${j}`}
            href={`mailto:${subPart}`}
            className="text-[#1260B2] hover:underline font-medium"
          >
            {subPart}
          </a>
        );
      }

      return subPart;
    });
  });
};

